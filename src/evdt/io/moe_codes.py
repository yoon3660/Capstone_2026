def is_fast(chger_type: str, output_kw: float | None) -> bool:
    """급속 충전기인가.

    output(충전용량 kW)이 있으면 그걸 우선 믿는다 — 우리 시뮬레이션에서
    실제로 필요한 값은 타입 이름이 아니라 kW 다.
    output 이 비어 있을 때만 타입 코드로 보조 판정한다.
    """
    if output_kw is not None and output_kw > 0:
        return output_kw >= FAST_CHARGER_MIN_KW
    return chger_type not in SLOW_CHGER_TYPES


