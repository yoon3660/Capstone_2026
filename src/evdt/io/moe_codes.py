def label(table: dict[str, str], code: str) -> str:
    """코드를 사람이 읽는 이름으로. 모르는 코드는 원본 그대로 돌려준다.

    가이드가 개정되어 새 코드가 생겼을 때 조용히 빈칸이 되지 않고
    `04(?)` 처럼 눈에 띄게 만든다.
    """
    code = (code or "").strip()
    if not code:
        return "(빈값)"
    name = table.get(code)
    return f"{code} {name}" if name else f"{code}(미등록코드)"


def unknown_codes(table: dict[str, str], codes: list[str]) -> set[str]:
    """코드표에 없는 값을 찾는다. 가이드 개정 감지용."""
    return {c for c in codes if c and c.strip() and c.strip() not in table}
